// ЗАЩИТА ОТ ИНЪЕКЦИЙ.
//
// Модель получает системную инструкцию, вопрос человека и найденные документы
// ОДНИМ потоком текста. Границы между ними она не чувствует. Значит текст
// внутри документа может прикинуться командой — и модель его выполнит.
//
// Это не лечится обновлением модели: причина в том, что у текста нет признака
// "это данные, а не инструкция". Защита строится снаружи, в три слоя:
//   1) пометить подозрительные места при загрузке документа;
//   2) обернуть документы явной границей, чтобы модель видела, где данные;
//   3) запретить в системной инструкции исполнять команды из этой зоны.

import type { Chunk, TrailEntry } from "./types.ts";

