/** Перед проверкой убираем приёмы маскировки: невидимые символы, полноширинные и «ломаные» буквы (NFKC), лишние пробелы. */
function normalizeForScan(text: string): string {
  return text
    .normalize("NFKC")
    .replace(/[\u200b-\u200f\u2060\u2062-\u2064\ufeff\u00ad]/g, "")
    .replace(/[\u202a-\u202e\u2066-\u2069]/g, "");
}

export interface Finding {
  label: string;
  excerpt: string;
}

/** Ищет спрятанные команды в тексте. Ничего не меняет — только помечает. */
export function scan(textIn: string): Finding[] {
  const text = normalizeForScan(textIn);
  const out: Finding[] = [];
  for (const { re, label } of PATTERNS) {
    const m = text.match(re);
    if (m && m.index !== undefined) {
      out.push({ label, excerpt: text.slice(m.index, m.index + 60).replace(/\s+/g, " ").trim() });
    }
  }
  return out;
}

/**
 * Готовит документы к передаче в модель: явная граница + пометки находок.
 * Возвращает блок текста и записи для журнала.
 */
export function wrapForModel(chunks: Chunk[]): {
  block: string;
  findings: Finding[];
  trail: TrailEntry[];
} {
  const findings: Finding[] = [];
  const trail: TrailEntry[] = [];
  const parts: string[] = [];

  for (const c of chunks) {
    // Находки в самом абзаце ПЛЮС пометка, унаследованная от документа.
    const f = scan(c.text);
    const suspect = f.length > 0 || c.tainted === true;
    if (suspect) {
      findings.push(...f);
      trail.push({
        at: new Date().toISOString(),
        actorId: "system",
        action: "injection-detected",
        detail:
          `"${c.docTitle}": ` +
          (f.length > 0
            ? f.map((x) => x.label).join(", ")
            : "документ помечен при загрузке"),
        flagged: true,
      });
    }
    const mark = suspect ? " ВНИМАНИЕ: СОДЕРЖИТ ПОХОЖЕЕ НА КОМАНДУ" : "";
    parts.push(
      `<<<ДОКУМЕНТ id="${c.docId}" название="${c.docTitle}"${mark}>>>\n` +
        `${c.text}\n` +
        `<<<КОНЕЦ ДОКУМЕНТА id="${c.docId}">>>`,
    );
  }

  return { block: parts.join("\n\n"), findings, trail };
}

